"""Regenerates engine/src/pe/pe_ordinal_names.inc from pefile's own ordinal-name tables.

    make_pe_ordinal_names.py <directory of an unpacked pefile wheel> [--out FILE]

pefile names imports by ordinal of three DLLs (oleaut32.dll, ws2_32.dll, wsock32.dll) from
tables in its `ordlookup` package (pefile.py: parse_import_directory and
parse_delay_import_directory call ordlookup.ordLookup). The reviewer did not accept "the
reader reports the ordinal instead" as a difference (board B-3620): the tables are copied as
DATA, and this script is how the copy is made and can be made again.

The table files are READ as text and parsed with `ast` (a dictionary literal of
ordinal -> bytes name); nothing of pefile is imported or executed. The SHA-256 of each
source file is printed and written into the generated file, so the copy is pinned to the
exact pefile release it was taken from.
"""
import ast
import hashlib
import os
import sys

TABLES = (('oleaut32.dll', 'oleaut32.py', 'kOrdinalNamesOleaut32'),
          ('ws2_32.dll', 'ws2_32.py', 'kOrdinalNamesWs2_32'),
          ('wsock32.dll', 'wsock32.py', 'kOrdinalNamesWsock32'))


def read_table(path):
    with open(path, 'rb') as f:
        raw = f.read()
    tree = ast.parse(raw.decode('utf-8'))
    for node in tree.body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and getattr(node.targets[0], 'id', None) == 'ord_names'):
            table = ast.literal_eval(node.value)
            break
    else:
        raise SystemExit(f'{path}: no ord_names table')
    out = {}
    for ordinal, name in table.items():
        if not isinstance(ordinal, int) or not 0 <= ordinal <= 0xFFFF or not isinstance(name, bytes):
            raise SystemExit(f'{path}: unexpected entry {ordinal!r}: {name!r}')
        text = name.decode('ascii')
        if not text or any(not (c.isalnum() or c in '_@?$') for c in text):
            raise SystemExit(f'{path}: name with an unexpected character: {text!r}')
        out[ordinal] = text
    return out, hashlib.sha256(raw).hexdigest()


def pefile_version(wheel_dir):
    for name in sorted(os.listdir(wheel_dir)):
        if name.startswith('pefile-') and name.endswith('.dist-info'):
            return name[len('pefile-'):-len('.dist-info')]
    return 'unknown'


def main():
    if len(sys.argv) not in (2, 4) or (len(sys.argv) == 4 and sys.argv[2] != '--out'):
        print(__doc__)
        return 2
    wheel_dir = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = sys.argv[3] if len(sys.argv) == 4 else os.path.join(os.path.dirname(here), 'src', 'pe',
                                                                   'pe_ordinal_names.inc')
    version = pefile_version(wheel_dir)
    lookup = os.path.join(wheel_dir, 'ordlookup', '__init__.py')
    with open(lookup, 'rb') as f:
        lookup_hash = hashlib.sha256(f.read()).hexdigest()
    lines = ['// Derived work: follows pefile 2024.8.26 (https://github.com/erocarrera/pefile), Copyright (c)',
             '// 2004-2024 Ero Carrera, MIT License. Changes made: its parsing rules re-implemented in C++; the',
             '// ordinal name tables copied unchanged. Full notice in THIRD-PARTY-NOTICES. This file: Apache',
             '// License 2.0, Copyright 2026 Dexmond Technologies.',
             '//',
             '// GENERATED by engine/tools/make_pe_ordinal_names.py. Do not edit by hand.',
             f'// Source: pefile {version}, package `ordlookup` (ordinal -> name tables for three DLLs).',
             '// pefile gives an import by ordinal of these DLLs the name from its table, or "ord<N>" when',
             '// the ordinal is not in the table (ordlookup/__init__.py: ordLookup, formatOrdString).',
             '// SHA-256 of the source files this copy was taken from:',
             f'//   ordlookup/__init__.py  {lookup_hash}']
    blocks = []
    for dll, file_name, symbol in TABLES:
        table, digest = read_table(os.path.join(wheel_dir, 'ordlookup', file_name))
        print(f'ordlookup/{file_name}  sha256 {digest}  {len(table)} names')
        lines.append(f'//   ordlookup/{file_name:<12} {digest}  ({len(table)} names, for {dll})')
        block = [f'static constexpr OrdinalName {symbol}[] = {{']
        block += [f'    {{{ordinal}, "{table[ordinal]}"}},' for ordinal in sorted(table)]
        block.append('};')
        blocks.append('\n'.join(block))
    print(f'ordlookup/__init__.py  sha256 {lookup_hash}')
    text = '\n'.join(lines) + '\n\n' + '\n\n'.join(blocks) + '\n'
    with open(out_path, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    print(f'wrote {out_path} (pefile {version})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
